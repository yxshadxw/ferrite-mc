/// Generated protocol ids of the `minecraft:data_component_type` registry.
///
/// `component_ids::DAMAGE` and friends name the ids; [`COMPONENT_COUNT`] is the number of
/// registered types. Regenerated by `build.rs` from `reports/registries.json`.
pub mod component_ids {
    include!(concat!(env!("OUT_DIR"), "/component_ids.rs"));
}

/// Errors from the item stack NBT save format.
#[derive(Debug, thiserror::Error)]
pub enum Error {
    /// The item stack compound has no `id`.
    #[error("item stack is missing `id`")]
    MissingId,
    /// The `id` tag is not a string.
    #[error("item stack `id` must be an NBT string")]
    InvalidId,
    /// The `id` names an item that is not in the `minecraft:item` registry.
    #[error("unknown item {0:?}")]
    UnknownItem(String),
    /// The item protocol id is not in the `minecraft:item` registry.
    #[error("unknown item protocol id {0}")]
    UnknownItemId(u16),
    /// The `count` tag is not an int.
    #[error("item stack `count` must be an NBT int")]
    InvalidCount,
    /// The count is outside the range vanilla accepts.
    #[error("item stack count {0} is outside 0..={max}", max = MAX_COUNT)]
    CountOutOfRange(i32),
    /// The `components` tag is not a compound.
    #[error("item stack `components` must be an NBT compound")]
    InvalidComponents,
    /// A component key names a type that is not in the `minecraft:data_component_type` registry.
    #[error("unknown data component {0:?}")]
    UnknownComponent(String),
    /// A component type id is not in the `minecraft:data_component_type` registry.
    #[error("unknown data component type id {0}")]
    UnknownComponentId(u16),
    /// A typed component is stored under another component type's id, which would encode to the
    /// wrong component.
    #[error("component {kind} cannot be stored under data component type id {id}")]
    ComponentIdMismatch { kind: &'static str, id: u16 },
}
