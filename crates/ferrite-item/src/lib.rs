//! Minecraft Java 26.3 item stacks and data components.
//!
//! An [`ItemStack`] is an item protocol id, a count and a [`ComponentPatch`]. The patch holds
//! only what the stack changes relative to the item's default components: the components it
//! adds or overrides, and the component types it removes.
//!
//! # Component types
//!
//! Component types are the entries of the `minecraft:data_component_type` registry (122 in
//! 26.3). [`component_ids`] names their protocol ids, and [`component_type`], [`component_id`]
//! and [`component_name`] translate between ids and names. [`Component`] has typed variants for
//! the components the server needs first-class, such as `custom_name`, `damage`, `food` and
//! `tool`. Every other type, and any value whose NBT shape does not match a typed variant, is
//! kept as [`Component::Opaque`] raw NBT, so a stack can always be re-encoded without losing
//! data.
//!
//! # Default components
//!
//! The 26.3 data generator writes no `reports/items.json`; it writes one file per item under
//! `reports/minecraft/components/item/<name>.json` holding that item's full default component
//! set. `build.rs` compiles those files into a static table ([`ItemDefaults`]) plus a single
//! embedded NBT blob, so no JSON is parsed at runtime. [`item_defaults`] gives the hot-path
//! columns (`max_stack_size`, `max_damage`, `rarity`) and [`default_components`] the complete
//! default set as raw NBT keyed by component type id.
//!
//! # NBT save format
//!
//! [`ItemStack::to_nbt`] and [`ItemStack::from_nbt`] use the 26.3 item save format:
//!
//! ```snbt
//! {id: "minecraft:diamond_sword", count: 1, components: {"minecraft:damage": 3, "!minecraft:food": {}}}
//! ```
//!
//! `components` lists patch entries only, and a `!` prefixed key removes that component from
//! the item's defaults. An empty stack encodes as `{id: "minecraft:air", count: 0}`.

